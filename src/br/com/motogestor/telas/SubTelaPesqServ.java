    private void pesquisarServico() {

        String sql = "select idservico as ID, servico as SERVIÇO, valor as VALOR "
                + "from tbservicos where servico like ?";

        try {
            pst = conexao.prepareStatement(sql);
            pst.setString(1, txtPesqServ.getText() + "%");
            rs = pst.executeQuery();
            tblServicos.setModel(DbUtils.resultSetToTableModel(rs));

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);

        } finally {
            //fecharConexao();
        }
    }

    private void selecionarServico() {

        int linha = tblServicos.getSelectedRow();

        if (linha >= 0) {

            servicoSelecionado = tblServicos.getValueAt(linha, 1).toString(); // Serviço
            valorSelecionado = tblServicos.getValueAt(linha, 2).toString(); // Valor

            dispose(); // fecha a tela
            //fecharConexao();

        } else {
            JOptionPane.showMessageDialog(this, "Selecione um serviço!");
        }
    }

